#!/usr/bin/env bash
# Mutation test for gen-contract.yml.
#
# A gate nobody can make fail is not a gate. This breaks the tree one rule at a
# time, asserts that the matching rule reports it, and restores the file. Every
# rule in the contract has a case here; a rule without one is only known to be
# green, not known to work. Add a case when you add a rule.
#
#   ./scripts/test-gen-contract.sh
#
# Mutations are applied to tracked files and reverted with `git checkout --`.
# A case refuses to touch a file that already has uncommitted changes, so a
# revert can never eat work in progress. The rest of the worktree may be dirty.
#
# The cases locate a victim file by glob, so the script works on any solution
# the contract describes. A case whose victim does not exist yet (no handler
# base, say) is reported SKIP, not failed.

set -uo pipefail
cd "$(git rev-parse --show-toplevel)"

CHECK="./scripts/check-gen-contract.sh --quiet --only"
pass=0; fail=0; skip=0
TOUCHED=()
CREATED=()

cleanup() {
  [ ${#TOUCHED[@]} -gt 0 ] && git checkout -- "${TOUCHED[@]}" 2>/dev/null
  for f in ${CREATED[@]+"${CREATED[@]}"}; do
    git rm -q --cached "$f" 2>/dev/null; rm -f "$f"
  done
  return 0
}
trap cleanup EXIT

# verdict <rule> <what>  — run the one rule and grade: exit 1 is the catch we
# want; exit 0 is a miss; exit 2 means the checker could not run (an unknown
# rule id, a broken contract) and is a failure too, never a silent pass.
verdict() {
  local rule="$1" what="$2" rc=0
  $CHECK "$rule" >/dev/null 2>&1 || rc=$?
  case "$rc" in
    1) echo "  ok    $rule"; pass=$((pass+1)) ;;
    0) echo "  MISS  $rule did not catch $what"; fail=$((fail+1)) ;;
    *) echo "  ERR   $rule: the checker could not run (exit $rc) — is the rule in gen-contract.yml?"; fail=$((fail+1)) ;;
  esac
}

# first_tracked <glob>  — the first tracked path matching the glob, or empty.
first_tracked() { git ls-files -- "$1" | head -1; }

# expect_fail <rule> <file> <sed-program>  — mutate, assert the rule fails, revert.
expect_fail() {
  local rule="$1" file="$2" prog="$3"
  if [ -z "$file" ]; then
    echo "  SKIP  $rule — no file to mutate"; skip=$((skip+1)); return
  fi
  if ! git diff --quiet -- "$file" || ! git diff --cached --quiet -- "$file"; then
    echo "  SKIP  $rule — $file has uncommitted changes"; skip=$((skip+1)); return
  fi
  TOUCHED+=("$file")
  sed -i.bak "$prog" "$file" && rm -f "$file.bak"
  verdict "$rule" "its mutation in $file"
  git checkout -- "$file"
}

# expect_fail_newfile <rule> <path> <content>  — add a file, assert the rule fails, remove it.
expect_fail_newfile() {
  local rule="$1" path="$2" content="$3"
  if [ -e "$path" ]; then
    echo "  SKIP  $rule — $path already exists"; skip=$((skip+1)); return
  fi
  mkdir -p "$(dirname "$path")"; printf '%s\n' "$content" > "$path"
  git add -N "$path" >/dev/null
  CREATED+=("$path")
  verdict "$rule" "new file $path"
  git rm -q --cached "$path" 2>/dev/null; rm -f "$path"
}

# expect_fail_delete <rule> <file>  — remove a file from the index, assert the rule fails, restore.
expect_fail_delete() {
  local rule="$1" file="$2"
  if [ -z "$file" ]; then
    echo "  SKIP  $rule — no file to remove"; skip=$((skip+1)); return
  fi
  if ! git diff --quiet -- "$file" || ! git diff --cached --quiet -- "$file"; then
    echo "  SKIP  $rule — $file has uncommitted changes"; skip=$((skip+1)); return
  fi
  TOUCHED+=("$file")
  rm -f "$file"
  verdict "$rule" "the removal of $file"
  git checkout -- "$file"
}

echo "gen-contract mutation test"
echo "  sanity: the contract is green before any mutation"
if ! ./scripts/check-gen-contract.sh --quiet >/dev/null 2>&1; then
  echo "  the contract is already red; fix that first (./scripts/check-gen-contract.sh)"; exit 1
fi

GEN_CS="$(first_tracked '*/gen-src/*.g.cs')"
DOMAIN_GEN="$(first_tracked '*.Domain/gen-src/*.g.cs')"
INFRA_GEN="$(first_tracked '*.Infrastructure/gen-src/*.g.cs')"
API_GEN="$(first_tracked '*.Api/gen-src/*.g.cs')"
DOMAIN_CSPROJ="$(first_tracked '*.Domain/*.csproj')"
INFRA_CSPROJ="$(first_tracked '*.Infrastructure/*.csproj')"
SRC_CS="$(first_tracked '*/src/*.cs')"
HANDLER_BASE="$(first_tracked '*/gen-src/*HandlerBase.g.cs')"
APPSVC_BASE="$(first_tracked '*/gen-src/*ApplicationServiceBase.g.cs')"
PREFIX="${DOMAIN_CSPROJ%%.Domain/*}"

# Markers and layout
expect_fail_newfile GEN-001 "${GEN_CS%/*}/NotGenerated.cs" "#nullable enable"
expect_fail GEN-002 "$GEN_CS" '1s/^#nullable enable$/#nullable disable/'
expect_fail GEN-003 "$GEN_CS" 's#// <auto-generated#// <hand-edited#'
expect_fail_newfile GEN-004 "${SRC_CS%/*}/Stale.g.cs" "#nullable enable"
expect_fail_newfile GEN-005 "${GEN_CS%/*}/README.md" "notes"

# Layering
expect_fail GEN-010 "$DOMAIN_GEN" "1a\\
using ${PREFIX}.Infrastructure.DbContexts;"
expect_fail GEN-011 "$INFRA_GEN" "1a\\
using ${PREFIX}.Api.Controllers;"
expect_fail GEN-012 "$API_GEN" "1a\\
using ${PREFIX}.Infrastructure.DbContexts;"
expect_fail GEN-013 "$DOMAIN_CSPROJ" "s#</Project>#<ItemGroup><ProjectReference Include=\"..\\\\${PREFIX}.Api\\\\${PREFIX}.Api.csproj\" /></ItemGroup></Project>#"
expect_fail GEN-014 "$INFRA_CSPROJ" "s#</Project>#<ItemGroup><ProjectReference Include=\"..\\\\${PREFIX}.Api\\\\${PREFIX}.Api.csproj\" /></ItemGroup></Project>#"

# Host wiring
expect_fail GEN-020 Directory.Build.props 's#gen-src\\\*\*\\\*\.cs#generated\\**\\*.cs#'
expect_fail GEN-021 .gitignore '/^\*\.generated-paths\.json$/d'

# Hand-written code
expect_fail GEN-030 "$SRC_CS" '1i\
// Generated by the Specfuse Generator (https://github.com/specfuse/generator)'

# Extension points
if [ -n "$HANDLER_BASE" ]; then
  expect_fail_newfile GEN-040 "${HANDLER_BASE%/*}/UnadoptedHandlerBase.g.cs" "#nullable enable"
else
  echo "  SKIP  GEN-040 — no *HandlerBase.g.cs in the tree yet"; skip=$((skip+1))
fi
if [ -n "$APPSVC_BASE" ]; then
  expect_fail_newfile GEN-041 "${APPSVC_BASE%/*}/UnadoptedApplicationServiceBase.g.cs" "#nullable enable"
else
  echo "  SKIP  GEN-041 — no *ApplicationServiceBase.g.cs in the tree yet"; skip=$((skip+1))
fi
expect_fail_newfile GEN-042 "${SRC_CS%/*}/DirectHandler.cs" "public sealed class DirectHandler : IOrderPlacedHandler { }"

echo
echo "  $pass ok, $fail missed, $skip skipped"
[ "$fail" -eq 0 ]
